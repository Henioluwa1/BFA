-- 3. Create Inspections Table
CREATE TABLE IF NOT EXISTS inspections (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspection_code VARCHAR(50) NOT NULL UNIQUE,
  reservation_id INT NULL,
  guest_id INT NULL,
  property_id INT NOT NULL,
  apartment_id INT NOT NULL,
  inspector_id INT NOT NULL,
  inspection_type VARCHAR(50) NOT NULL DEFAULT 'CHECKOUT' CHECK (inspection_type IN ('PRE_CHECKIN', 'CHECKOUT', 'ROUTINE', 'DAMAGE', 'MAINTENANCE_REVIEW')),
  condition_rating VARCHAR(50) NOT NULL DEFAULT 'GOOD' CHECK (condition_rating IN ('EXCELLENT', 'GOOD', 'FAIR', 'POOR', 'DAMAGED')),
  damage_items JSONB NULL,
  missing_items JSONB NULL,
  notes TEXT NULL,
  evidence JSONB NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'IN_PROGRESS', 'COMPLETED', 'FOLLOW_UP')),
  scheduled_date DATE NOT NULL,
  completed_at TIMESTAMPTZ NULL,
  created_by INT NULL,
  updated_by INT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE SET NULL,
  FOREIGN KEY (guest_id) REFERENCES guests(id) ON DELETE SET NULL,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE,
  FOREIGN KEY (apartment_id) REFERENCES apartments(id) ON DELETE CASCADE,
  FOREIGN KEY (inspector_id) REFERENCES users(id)

);

CREATE INDEX IF NOT EXISTS idx_insp_status ON inspections (status);
