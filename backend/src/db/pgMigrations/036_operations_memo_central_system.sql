-- 1. Central Operations Table
CREATE TABLE IF NOT EXISTS central_operations (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_code VARCHAR(50) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  category VARCHAR(60) NOT NULL CHECK (category IN (
    'ADMINISTRATIVE_DIRECTIVE',
    'PROPERTY_OPERATIONS',
    'MAINTENANCE_INSPECTION',
    'FRONT_OFFICE_RECEPTION',
    'STAFF_ASSIGNMENT',
    'OPERATIONAL_IMPROVEMENT',
    'COMPLIANCE_POLICY',
    'EMERGENCY_OPERATION',
    'MANAGEMENT_COMMUNICATION'
  )),
  priority VARCHAR(20) NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('NORMAL', 'IMPORTANT', 'URGENT', 'CRITICAL')),
  status VARCHAR(50) NOT NULL DEFAULT 'ISSUED' CHECK (status IN (
    'DRAFT', 'ISSUED', 'PENDING_DELIVERY', 'DELIVERED', 'AWAITING_ACKNOWLEDGEMENT',
    'ACKNOWLEDGED', 'IN_PROGRESS', 'AWAITING_CLARIFICATION', 'BLOCKED', 'AWAITING_REVIEW',
    'COMPLETED', 'REJECTED', 'CANCELLED', 'OVERDUE', 'ESCALATED', 'CLOSED'
  )),
  initiated_by_user_id INT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  property_id INT NULL REFERENCES properties(id) ON DELETE SET NULL,
  target_audience_type VARCHAR(50) NOT NULL CHECK (target_audience_type IN (
    'MANAGERS_ONLY', 'SPECIFIC_USER', 'SPECIFIC_USERS', 'PROPERTY_STAFF', 'PROPERTY_RECEPTIONISTS', 'PROPERTY_ALL', 'DEPARTMENT_GROUP'
  )),
  subject VARCHAR(255) NOT NULL,
  purpose TEXT NOT NULL,
  operational_instructions TEXT NOT NULL,
  expected_outcome TEXT NULL,
  responsibility_definition TEXT NULL,
  reporting_requirements TEXT NULL,
  deadline_at TIMESTAMPTZ NULL,
  effective_from TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  chat_thread_id INT NULL REFERENCES chat_threads(id) ON DELETE SET NULL,
  chat_message_id INT NULL REFERENCES chat_messages(id) ON DELETE SET NULL,
  latest_memo_id INT NULL,
  supervisor_user_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  completed_at TIMESTAMPTZ NULL,
  closed_at TIMESTAMPTZ NULL,
  cancelled_at TIMESTAMPTZ NULL,
  cancellation_reason TEXT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

