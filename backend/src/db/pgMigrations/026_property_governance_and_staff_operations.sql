-- 10. Decoupled Housekeeping & Maintenance from Occupancy
-- Keep each object independently retryable. TiDB validates each ALTER against
-- the table schema at the start of that statement, so dependent columns and
-- the index must be added only referenced columns exist.
ALTER TABLE apartments ADD COLUMN IF NOT EXISTS housekeeping_status VARCHAR(50) NOT NULL DEFAULT 'INSPECTED_READY';
DO $$ BEGIN
  ALTER TABLE apartments ADD CONSTRAINT chk_apartments_housekeeping_status CHECK (housekeeping_status IN ('DIRTY', 'CLEANING_IN_PROGRESS', 'CLEANED', 'INSPECTED_READY'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

ALTER TABLE apartments ADD COLUMN IF NOT EXISTS maintenance_status VARCHAR(50) NOT NULL DEFAULT 'OPERATIONAL';
DO $$ BEGIN
  ALTER TABLE apartments ADD CONSTRAINT chk_apartments_maintenance_status CHECK (maintenance_status IN ('OPERATIONAL', 'INSPECTION_REQUIRED', 'UNDER_REPAIR', 'OUT_OF_ORDER'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

