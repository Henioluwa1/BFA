-- 1. Capabilities Table
CREATE TABLE IF NOT EXISTS capabilities (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) NULL,
  category VARCHAR(50) NOT NULL DEFAULT 'GENERAL',
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  restriction_level VARCHAR(50) NOT NULL DEFAULT 'NONE' CHECK (restriction_level IN ('NONE', 'MANAGER_RESTRICTED', 'OWNER_RESTRICTED', 'ROLE_RESTRICTED')),
  restricted_by_id INT NULL,
  restricted_by_role VARCHAR(50) NULL,
  restricted_at TIMESTAMPTZ NULL,
  restriction_reason TEXT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP

);

CREATE INDEX IF NOT EXISTS idx_cap_name ON capabilities (name);
CREATE INDEX IF NOT EXISTS idx_cap_enabled ON capabilities (is_enabled);
CREATE INDEX IF NOT EXISTS idx_cap_restriction ON capabilities (restriction_level);

-- 2. Access Approval Requests Table (Super Admin request to Owner)
CREATE TABLE IF NOT EXISTS access_approval_requests (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capability_id INT NOT NULL,
  requested_by_id INT NOT NULL,
  target_role VARCHAR(50) NOT NULL DEFAULT 'OWNER',
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'BYPASSED_FORCE')),
  request_reason TEXT NOT NULL,
  requested_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  reviewed_by_id INT NULL,
  reviewed_at TIMESTAMPTZ NULL,
  review_notes TEXT NULL,
  FOREIGN KEY (capability_id) REFERENCES capabilities(id) ON DELETE CASCADE

);

CREATE INDEX IF NOT EXISTS idx_req_status ON access_approval_requests (status);
CREATE INDEX IF NOT EXISTS idx_req_capability ON access_approval_requests (capability_id);

-- 3. Access Overrides Table
CREATE TABLE IF NOT EXISTS access_overrides (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capability_id INT NOT NULL,
  override_type VARCHAR(50) NOT NULL CHECK (override_type IN ('OWNER_APPROVED', 'SUPER_ADMIN_FORCED')),
  applied_by_id INT NOT NULL,
  applied_by_role VARCHAR(50) NOT NULL,
  reason TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (capability_id) REFERENCES capabilities(id) ON DELETE CASCADE

);

CREATE INDEX IF NOT EXISTS idx_ovr_cap_active ON access_overrides (capability_id, is_active);

