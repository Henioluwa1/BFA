CREATE TABLE IF NOT EXISTS automation_confirmations (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  confirmation_token VARCHAR(64) NOT NULL UNIQUE,
  action_id VARCHAR(100) NOT NULL,
  user_id INT NOT NULL,
  user_role VARCHAR(50) NOT NULL,
  property_id INT NULL,
  record_id VARCHAR(100) NULL,
  parameters_hash VARCHAR(64) NOT NULL,
  parameters_payload JSONB NOT NULL,
  summary VARCHAR(255) NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'EXPIRED', 'EXECUTED')),
  requires_dual_approval BOOLEAN NOT NULL DEFAULT FALSE,
  approver_id INT NULL,
  approver_role VARCHAR(50) NULL,
  approved_at TIMESTAMPTZ NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  executed_at TIMESTAMPTZ NULL,
  idempotency_key VARCHAR(100) NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE

);

CREATE INDEX IF NOT EXISTS idx_auto_conf_token ON automation_confirmations (confirmation_token);
CREATE INDEX IF NOT EXISTS idx_auto_conf_user_status ON automation_confirmations (user_id, status);
CREATE INDEX IF NOT EXISTS idx_auto_conf_expires ON automation_confirmations (expires_at);
CREATE INDEX IF NOT EXISTS idx_auto_conf_idempotency ON automation_confirmations (idempotency_key);
