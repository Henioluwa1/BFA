-- 4. Chat Message Receipts Table (Auxiliary Per-Message Status for 1-to-1 DMs)
CREATE TABLE IF NOT EXISTS chat_message_receipts (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id INT NOT NULL,
  user_id INT NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'DELIVERED' CHECK (status IN ('SENT', 'DELIVERED', 'READ')),
  delivered_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
