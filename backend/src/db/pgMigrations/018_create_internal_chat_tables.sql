-- 1. Chat Threads Table (Direct Conversations & Property Team Channels)
CREATE TABLE IF NOT EXISTS chat_threads (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_type VARCHAR(50) NOT NULL CHECK (thread_type IN ('DIRECT', 'PROPERTY_CHANNEL', 'SYSTEM_BROADCAST')),
  property_id INT NULL ,
  title VARCHAR(150) NULL ,
  created_by INT NOT NULL,
  direct_hash VARCHAR(64) NULL UNIQUE ,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED', 'LOCKED')),
  last_message_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE RESTRICT,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT

);

CREATE INDEX IF NOT EXISTS idx_threads_prop_type ON chat_threads (property_id, thread_type);
CREATE INDEX IF NOT EXISTS idx_threads_last_msg ON chat_threads (last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_threads_created_by ON chat_threads (created_by);

-- 2. Chat Thread Participants Table (Membership & Monotonic Read Watermarks)
CREATE TABLE IF NOT EXISTS chat_thread_participants (

  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id INT NOT NULL,
  user_id INT NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('MEMBER', 'MODERATOR', 'ADMIN')),
  last_read_message_id INT NULL ,
  last_read_at TIMESTAMPTZ NULL,
  is_muted BOOLEAN NOT NULL DEFAULT FALSE,
  joined_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  left_at TIMESTAMPTZ NULL ,
  FOREIGN KEY (thread_id) REFERENCES chat_threads(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT uq_thread_user UNIQUE (thread_id, user_id)

);

CREATE INDEX IF NOT EXISTS idx_participant_user ON chat_thread_participants (user_id, left_at);
CREATE INDEX IF NOT EXISTS idx_participant_watermark ON chat_thread_participants (thread_id, user_id, last_read_message_id);

-- 3. Chat Messages Table (Authoritative Message Sequence & Idempotency)
