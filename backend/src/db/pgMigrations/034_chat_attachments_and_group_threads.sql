-- 1. Relax/extend thread_type check constraint in chat_threads to allow 'GROUP'
DO $$
BEGIN
  ALTER TABLE chat_threads DROP CONSTRAINT IF EXISTS chat_threads_thread_type_check;
  ALTER TABLE chat_threads ADD CONSTRAINT chat_threads_thread_type_check 
    CHECK (thread_type IN ('DIRECT', 'PROPERTY_CHANNEL', 'SYSTEM_BROADCAST', 'GROUP'));
EXCEPTION
  WHEN OTHERS THEN
    NULL;
END $$;

-- 2. Relax/extend message_type check constraint in chat_messages to allow 'IMAGE', 'DOCUMENT', 'FILE'
DO $$
BEGIN
  ALTER TABLE chat_messages DROP CONSTRAINT IF EXISTS chat_messages_message_type_check;
  ALTER TABLE chat_messages ADD CONSTRAINT chat_messages_message_type_check 
    CHECK (message_type IN ('TEXT', 'CONTEXT_LINK', 'SYSTEM_NOTICE', 'IMAGE', 'DOCUMENT', 'FILE'));
EXCEPTION
  WHEN OTHERS THEN
    NULL;
END $$;

-- 3. Create chat_attachments table with PostgreSQL BYTEA binary storage for persistent blob retention
CREATE TABLE IF NOT EXISTS chat_attachments (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id INT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
  thread_id INT NOT NULL REFERENCES chat_threads(id) ON DELETE CASCADE,
  uploaded_by INT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  original_name VARCHAR(255) NOT NULL,
  storage_name VARCHAR(255) NOT NULL,
  file_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL,
  storage_driver VARCHAR(50) NOT NULL DEFAULT 'DB_BLOB',
  storage_path VARCHAR(500) NULL,
  file_data BYTEA NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chat_attachments_msg ON chat_attachments (message_id);
CREATE INDEX IF NOT EXISTS idx_chat_attachments_thread ON chat_attachments (thread_id);
CREATE INDEX IF NOT EXISTS idx_chat_attachments_uploader ON chat_attachments (uploaded_by);
