/**
 * PostgreSQL Migration Runner for BFA Apartments Management System
 * Uses Aiven PostgreSQL Connection Pool (pgPool) with transactional execution,
 * PostgreSQL advisory locking (pg_advisory_lock), and automated schema ledger tracking.
 */

const fs = require('fs');
const path = require('path');
const { getPgPool, closePgPool, sanitizeErrorMessage } = require('./pgPool');
const logger = require('../core/logging/logger');

const PG_MIGRATOR_LOCK_KEY = "bfa_pg_migrator_lock";

/**
 * Read-only inspection of PostgreSQL schema migration status without executing DDL.
 * Safe to execute at any time.
 * @param {object} poolInstance Optional pool override for testing
 * @returns {Promise<object>}
 */
async function checkPgMigrationStatus(poolInstance = null) {
  const pool = poolInstance || getPgPool();
  const migrationsDir = path.resolve(__dirname, 'pgMigrations');

  if (!fs.existsSync(migrationsDir)) {
    fs.mkdirSync(migrationsDir, { recursive: true });
  }

  const files = fs
    .readdirSync(migrationsDir)
    .filter((file) => file.endsWith('.sql'))
    .sort();

  const client = await pool.connect();
  try {
    // 1. Check if schema_migrations table exists
    const checkTableRes = await client.query(`
      SELECT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = current_schema() AND table_name = 'schema_migrations'
      ) AS table_exists;
    `);

    let appliedSet = new Set();
    if (checkTableRes.rows[0]?.table_exists) {
      const appliedRes = await client.query(
        'SELECT migration_name FROM schema_migrations ORDER BY id ASC;'
      );
      appliedSet = new Set(appliedRes.rows.map((r) => r.migration_name));
    }

    const pending = files.filter((file) => !appliedSet.has(file));

    return {
      isUpToDate: pending.length === 0,
      appliedCount: appliedSet.size,
      pendingCount: pending.length,
      pendingMigrations: pending,
      appliedMigrations: Array.from(appliedSet),
      totalMigrations: files.length,
    };
  } finally {
    client.release();
  }
}

/**
 * Executes pending PostgreSQL database migrations with advisory locking and transaction safety.
 * @param {object} poolInstance Optional pool override for testing
 * @returns {Promise<object>}
 */
async function runPgMigrations(poolInstance = null) {
  const pool = poolInstance || getPgPool();
  const migrationsDir = path.resolve(__dirname, 'pgMigrations');

  if (!fs.existsSync(migrationsDir)) {
    fs.mkdirSync(migrationsDir, { recursive: true });
  }

  const files = fs
    .readdirSync(migrationsDir)
    .filter((file) => file.endsWith('.sql'))
    .sort();

  logger.info(`Starting PostgreSQL migration check in: ${migrationsDir}`);

  const client = await pool.connect();
  let lockAcquired = false;

  try {
    // 1. Acquire PostgreSQL session advisory lock using hashtext
    logger.info(`Acquiring PostgreSQL advisory lock '${PG_MIGRATOR_LOCK_KEY}'...`);
    await client.query('SELECT pg_advisory_lock(hashtext($1));', [PG_MIGRATOR_LOCK_KEY]);
    lockAcquired = true;
    logger.info('PostgreSQL advisory lock acquired successfully.');

    // 2. Ensure schema_migrations table exists
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        migration_name VARCHAR(255) NOT NULL UNIQUE,
        batch INT NOT NULL DEFAULT 1,
        executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE INDEX IF NOT EXISTS idx_pg_migration_name ON schema_migrations (migration_name);
    `);

    // 3. Fetch applied migrations
    const appliedRes = await client.query(
      'SELECT migration_name FROM schema_migrations ORDER BY id ASC;'
    );
    const appliedSet = new Set(appliedRes.rows.map((r) => r.migration_name));

    const pending = files.filter((file) => !appliedSet.has(file));

    if (pending.length === 0) {
      logger.info(`PostgreSQL database is up to date (${appliedSet.size}/${files.length} applied). No pending migrations.`);
      return {
        appliedCount: 0,
        totalMigrations: files.length,
        batch: 0,
        isUpToDate: true,
      };
    }

    logger.info(`Found ${pending.length} pending PostgreSQL migration(s) to execute.`);

    // 4. Determine next batch number
    const batchRes = await client.query(
      'SELECT COALESCE(MAX(batch), 0) + 1 AS next_batch FROM schema_migrations;'
    );
    const nextBatch = parseInt(batchRes.rows[0]?.next_batch, 10) || 1;

    let appliedCount = 0;
    for (const file of pending) {
      const filePath = path.join(migrationsDir, file);
      const sql = fs.readFileSync(filePath, 'utf8');

      logger.info(`Applying PostgreSQL migration: ${file}...`);
      await client.query('BEGIN');

      try {
        await client.query(sql);
        await client.query(
          'INSERT INTO schema_migrations (migration_name, batch) VALUES ($1, $2);',
          [file, nextBatch]
        );
        await client.query('COMMIT');
        logger.info(`Successfully applied: ${file}`);
        appliedCount++;
      } catch (err) {
        await client.query('ROLLBACK');
        const sanitizedErr = sanitizeErrorMessage(err.message);
        logger.error(`PostgreSQL migration failed at ${file}: ${sanitizedErr}`, {
          file,
          code: err.code,
        });
        const error = new Error(`Migration failed at ${file}: ${sanitizedErr}`);
        error.code = err.code;
        throw error;
      }
    }

    // 5. Synchronize identity sequences for any seeded tables
    try {
      await client.query(`
        DO $$
        DECLARE
          seq RECORD;
        BEGIN
          FOR seq IN
            SELECT table_name, column_name, pg_get_serial_sequence(quote_ident(table_name), column_name) as seq_name
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND is_identity = 'YES'
          LOOP
            IF seq.seq_name IS NOT NULL THEN
              EXECUTE format('SELECT setval(%L, COALESCE((SELECT MAX(%I) FROM %I), 1))', seq.seq_name, seq.column_name, seq.table_name);
            END IF;
          END LOOP;
        END $$;
      `);
      logger.info('PostgreSQL identity sequences successfully synchronized.');
    } catch (seqErr) {
      logger.warn(`Notice: Identity sequence synchronization returned: ${seqErr.message}`);
    }

    logger.info(`Successfully executed ${appliedCount} PostgreSQL migration(s). Batch #${nextBatch}`);
    return {
      appliedCount,
      totalMigrations: files.length,
      batch: nextBatch,
      isUpToDate: true,
    };
  } finally {
    if (lockAcquired) {
      try {
        await client.query('SELECT pg_advisory_unlock(hashtext($1));', [PG_MIGRATOR_LOCK_KEY]);
        logger.info('PostgreSQL advisory lock cleanly released.');
      } catch (unlockErr) {
        logger.warn(`Warning during advisory lock release: ${unlockErr.message}`);
      }
    }
    client.release();
  }
}

// ─── CLI Entry Point ──────────────────────────────────────────────────────────
if (require.main === module) {
  const args = process.argv.slice(2);
  const isCheckMode = args.includes('--check') || args.includes('--status') || args.includes('status');

  if (isCheckMode) {
    checkPgMigrationStatus()
      .then((status) => {
        console.log('\n[POSTGRESQL MIGRATION STATUS]:');
        console.log(`  - Total Available: ${status.totalMigrations}`);
        console.log(`  - Applied:         ${status.appliedCount}`);
        console.log(`  - Pending:         ${status.pendingCount}`);
        console.log(`  - Up to Date:      ${status.isUpToDate ? 'YES' : 'NO'}`);
        if (status.pendingCount > 0) {
          console.log('\nPending Migrations:');
          status.pendingMigrations.forEach((m) => console.log(`  - ${m}`));
        }
        process.exit(0);
      })
      .catch((err) => {
        console.error('[POSTGRESQL MIGRATION STATUS ERROR]:', sanitizeErrorMessage(err.message));
        process.exit(1);
      })
      .finally(() => closePgPool());
  } else {
    runPgMigrations()
      .then((result) => {
        console.log('\n[POSTGRESQL MIGRATION COMPLETED]:');
        console.log(`  - Applied Migrations: ${result.appliedCount}`);
        console.log(`  - Total Migrations:   ${result.totalMigrations}`);
        console.log(`  - Batch Number:       ${result.batch}`);
        process.exit(0);
      })
      .catch((err) => {
        console.error('[POSTGRESQL MIGRATION FAILED]:', sanitizeErrorMessage(err.message));
        process.exit(1);
      })
      .finally(() => closePgPool());
  }
}

module.exports = {
  runPgMigrations,
  checkPgMigrationStatus,
  PG_MIGRATOR_LOCK_KEY,
};
