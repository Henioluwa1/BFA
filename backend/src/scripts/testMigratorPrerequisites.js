/**
 * Aiven PostgreSQL Migrator Prerequisites Test
 * Validates advisory locking, transactional DDL, and identity column behavior on live Aiven.
 */

require('dotenv').config();
const { getPgPool, closePgPool } = require('../db/pgPool');
const { PG_MIGRATOR_LOCK_KEY } = require('../db/pgMigrator');

async function testPrerequisites() {
  const pool = getPgPool();
  const client = await pool.connect();
  try {
    console.log('=== TESTING MIGRATOR PREREQUISITES ON LIVE AIVEN POSTGRESQL ===');

    // 1. Advisory Lock Test
    console.log(`Testing pg_advisory_lock with key '${PG_MIGRATOR_LOCK_KEY}'...`);
    await client.query('SELECT pg_advisory_lock(hashtext($1));', [PG_MIGRATOR_LOCK_KEY]);
    console.log('✓ Advisory lock successfully acquired.');

    // 2. Transactional DDL & Rollback Test
    console.log('Testing transactional DDL with BEGIN/ROLLBACK...');
    await client.query('BEGIN;');
    await client.query('CREATE TABLE _bfa_prereq_test (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, test_col VARCHAR(50));');
    await client.query('INSERT INTO _bfa_prereq_test (test_col) VALUES (\'test_val\');');
    const tempCheck = await client.query('SELECT COUNT(*) FROM _bfa_prereq_test;');
    console.log(`  Created test row count inside transaction: ${tempCheck.rows[0].count}`);
    await client.query('ROLLBACK;');
    console.log('✓ Transaction successfully rolled back.');

    // Verify table does not exist after rollback
    const afterCheck = await client.query(`
      SELECT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = '_bfa_prereq_test'
      ) AS exists;
    `);
    console.log(`  Table exists after rollback: ${afterCheck.rows[0].exists}`);
    if (afterCheck.rows[0].exists) {
      throw new Error('DDL was not rolled back!');
    }
    console.log('✓ Verified transactional DDL rollback works on live cluster.');

    // 3. Advisory Unlock Test
    await client.query('SELECT pg_advisory_unlock(hashtext($1));', [PG_MIGRATOR_LOCK_KEY]);
    console.log('✓ Advisory lock successfully released.');

    console.log('=== ALL MIGRATOR PREREQUISITES VERIFIED ON LIVE CLUSTER ===');
  } finally {
    client.release();
    await closePgPool();
  }
}

testPrerequisites().catch(e => {
  console.error('Prerequisites test failed:', e.message);
  process.exit(1);
});
