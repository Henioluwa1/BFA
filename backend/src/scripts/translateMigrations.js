/**
 * PostgreSQL Schema Migration Generator for BFA Apartments Management System
 * Automatically translates all 31 MySQL migrations into deterministic, production-grade
 * PostgreSQL migrations in backend/src/db/pgMigrations/.
 */

const fs = require('fs');
const path = require('path');

const srcDir = path.resolve(__dirname, '../db/migrations');
const dstDir = path.resolve(__dirname, '../db/pgMigrations');

if (!fs.existsSync(dstDir)) {
  fs.mkdirSync(dstDir, { recursive: true });
}

function translateMySqlToPostgreSql(sql, filename) {
  let out = sql;

  // 1. Remove MySQL table options and character set collations
  out = out.replace(/\)\s*ENGINE=InnoDB\s+DEFAULT\s+CHARSET=utf8mb4\s+COLLATE=utf8mb4_unicode_ci;/gi, ');');
  out = out.replace(/\)\s*ENGINE=InnoDB\s+DEFAULT\s+CHARSET=utf8mb4;/gi, ');');
  out = out.replace(/\)\s*ENGINE=InnoDB;/gi, ');');

  // 2. Remove backticks
  out = out.replace(/`([a-zA-Z0-9_]+)`/g, '$1');

  // 3. Remove MySQL COMMENT clauses
  out = out.replace(/COMMENT\s+'[^']*'/gi, '');

  // 4. Identity / Primary Key translation (PostgreSQL standard GENERATED BY DEFAULT AS IDENTITY)
  out = out.replace(/\bINT\s+AUTO_INCREMENT\s+PRIMARY\s+KEY\b/gi, 'INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  out = out.replace(/\bBIGINT\s+AUTO_INCREMENT\s+PRIMARY\s+KEY\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  out = out.replace(/\bINT\s+AUTO_INCREMENT\b/gi, 'INT GENERATED BY DEFAULT AS IDENTITY');
  out = out.replace(/\bBIGINT\s+AUTO_INCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY');

  // 5. Types translation
  out = out.replace(/\bTINYINT\(1\)\b/gi, 'BOOLEAN');
  out = out.replace(/\bDATETIME\b/gi, 'TIMESTAMPTZ');
  out = out.replace(/\bTIMESTAMP\s+DEFAULT\s+CURRENT_TIMESTAMP\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP\b/gi, 'TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP');
  out = out.replace(/\bTIMESTAMP\b/gi, 'TIMESTAMPTZ');
  out = out.replace(/\bJSON\b/gi, 'JSONB');
  out = out.replace(/\bDECIMAL\(/gi, 'NUMERIC(');

  // 6. DATEDIFF translation (MySQL: DATEDIFF(d1, d2) -> PostgreSQL: (d1 - d2))
  out = out.replace(/DATEDIFF\(\s*([a-zA-Z0-9_]+)\s*,\s*([a-zA-Z0-9_]+)\s*\)/gi, '($1 - $2)');

  // 7. Inline UNIQUE KEY to CONSTRAINT ... UNIQUE
  out = out.replace(/UNIQUE\s+KEY\s+([a-zA-Z0-9_]+)\s*\(([^)]+)\)/gi, 'CONSTRAINT $1 UNIQUE ($2)');

  // 8. Remove AFTER column clauses (invalid in PostgreSQL ALTER TABLE)
  out = out.replace(/\s+AFTER\s+[a-zA-Z0-9_]+/gi, '');

  // 8b. Ensure migration 004 has authoritative baseline users required for downstream FK references (011, 012, 013, 018)
  if (filename.includes('004_create_users_and_seed_auth') && !out.includes('INSERT INTO users')) {
    out += `\n-- Seed Authoritative Accounts (Non-Production Baseline Test Hash)
INSERT INTO users (id, name, email, password_hash, role, property_id, agent_id, status) VALUES
(1, 'BFA Super Admin', 'superadmin@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'SUPER_ADMIN', NULL, NULL, 'ACTIVE'),
(2, 'Sarah Jenkins (Admin)', 'admin@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'ADMIN', NULL, NULL, 'ACTIVE'),
(3, 'Marcus Vance (Manager)', 'manager@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'MANAGER', NULL, NULL, 'ACTIVE'),
(4, 'Elena Ramos (Reception)', 'receptionist@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'RECEPTIONIST', 1, NULL, 'ACTIVE'),
(5, 'David Kalu (Staff)', 'staff@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'STAFF', 1, NULL, 'ACTIVE'),
(6, 'Alexander Wright (Agent)', 'agent@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'AGENT', NULL, 1, 'ACTIVE'),
(7, 'Chief Emeka BFA (Owner)', 'owner@bfa.com', '$2b$10$GaII4sIWwHiOi1sCf149TOFCzwYPhwSNv7nAAUeSVs1FBC2A6.t3q', 'OWNER', NULL, NULL, 'ACTIVE')
ON CONFLICT (id) DO NOTHING;\n`;
  }

  // 8c. Include ROLE_RESTRICTED in capabilities.restriction_level check constraint (required by migration 028)
  if (filename.includes('006_access_control_and_capabilities')) {
    out = out.replace(
      /ENUM\('NONE',\s*'MANAGER_RESTRICTED',\s*'OWNER_RESTRICTED'\)/gi,
      "ENUM('NONE', 'MANAGER_RESTRICTED', 'OWNER_RESTRICTED', 'ROLE_RESTRICTED')"
    );
  }

  // 8d. In migration 030, convert boolean comparison is_verified = 0 to is_verified = FALSE
  if (filename.includes('030_kiosk_credential_security_and_geofence_review')) {
    out = out.replace(/is_verified\s*=\s*0/gi, 'is_verified = FALSE');
  }

  // 9. Specific migration dynamic SQL / prepared statement translations
  if (filename.includes('010_guests_and_inspections')) {
    const mysqlFkBlock = /-- information_schema[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_reservations_guest_fk;/gi;
    const pgFkBlock = `DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT fk_reservations_guest FOREIGN KEY (guest_id) REFERENCES guests(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(mysqlFkBlock, () => pgFkBlock);
  }

  if (filename.includes('011_maintenance_and_expenses')) {
    // Replace all 5 SET @fk_exists blocks
    const maintFkBlocks = /SET\s+@fk_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_maint_reservation_fk;/gi;
    const pgMaintFk = `DO $$ BEGIN
  ALTER TABLE maintenance_requests ADD CONSTRAINT fk_maint_reported_by FOREIGN KEY (reported_by_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE maintenance_requests ADD CONSTRAINT fk_maint_assigned_to FOREIGN KEY (assigned_to_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE maintenance_requests ADD CONSTRAINT fk_maint_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(maintFkBlocks, () => pgMaintFk);

    const payFkBlocks = /SET\s+@fk_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_pay_parent_fk;/gi;
    const pgPayFk = `DO $$ BEGIN
  ALTER TABLE payment_transactions ADD CONSTRAINT fk_pay_refunded_by FOREIGN KEY (refunded_by_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE payment_transactions ADD CONSTRAINT fk_pay_parent_txn FOREIGN KEY (parent_transaction_id) REFERENCES payment_transactions(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(payFkBlocks, () => pgPayFk);
  }

  if (filename.includes('012_agents_and_commissions')) {
    const agentFkBlock = /SET\s+@agent_fk_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_agent_property_fk;/gi;
    const pgAgentFk = `DO $$ BEGIN
  ALTER TABLE agents ADD CONSTRAINT fk_agent_property FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(agentFkBlock, () => pgAgentFk);
  }

  if (filename.includes('015_one_night_check_constraint')) {
    const checkBlock = /SET\s+@one_night_check_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+add_one_night_check_stmt;/gi;
    const pgCheck = `DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT chk_one_night_stay CHECK ((check_out_date - check_in_date) = 1);
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(checkBlock, () => pgCheck);
  }

  if (filename.includes('017_add_confirmation_token_to_reservations')) {
    const tokenBlock = /SET\s+@confirmation_token_column_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+ensure_confirmation_token_index_stmt;/gi;
    const pgToken = `ALTER TABLE reservations ADD COLUMN IF NOT EXISTS confirmation_token VARCHAR(64) NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_res_confirmation_token ON reservations (confirmation_token);`;
    out = out.replace(tokenBlock, () => pgToken);
  }

  if (filename.includes('021_accounting_account_mappings_portable')) {
    // 1. Convert all UPDATE ... JOIN ... SET to UPDATE ... SET ... FROM ... WHERE ...
    out = out.replace(
      /UPDATE\s+accounting_account_mappings\s+m\s+JOIN\s+chart_of_accounts\s+a\s+ON\s+a\.account_code\s*=\s*'([^']+)'\s+SET\s+m\.account_id\s*=\s*a\.id\s+WHERE\s+m\.mapping_key\s+([^;]+);/gi,
      "UPDATE accounting_account_mappings m SET account_id = a.id FROM chart_of_accounts a WHERE a.account_code = '$1' AND m.mapping_key $2;"
    );

    // 2. Convert index block
    const idxBlock = /SET\s+@exist[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt;/gi;
    const pgIdx = `CREATE INDEX IF NOT EXISTS idx_pay_provider_ref ON payment_transactions (provider, provider_reference);`;
    out = out.replace(idxBlock, () => pgIdx);
  }

  if (filename.includes('022_support_multinight_stays')) {
    const stayBlock = /SET\s+@check_one_night_stay_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+add_min_one_night_stmt;/gi;
    const pgStay = `ALTER TABLE reservations DROP CONSTRAINT IF EXISTS chk_one_night_stay;
ALTER TABLE reservations DROP CONSTRAINT IF EXISTS chk_one_night;
ALTER TABLE reservations DROP CONSTRAINT IF EXISTS chk_min_one_night;

DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT chk_min_one_night CHECK ((check_out_date - check_in_date) >= 1);
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(stayBlock, () => pgStay);
  }

  if (filename.includes('023_payment_provider_unique')) {
    const p1 = /SET\s+@unique_idx_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_drop_old_pay_idx;/gi;
    const r1 = `CREATE UNIQUE INDEX IF NOT EXISTS uq_pay_provider_ref ON payment_transactions (provider, provider_reference);
DROP INDEX IF EXISTS idx_pay_provider_ref;`;
    out = out.replace(p1, () => r1);

    const p2 = /SET\s+@property_fk_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_ape_property_fk;/gi;
    const r2 = `DO $$ BEGIN
  ALTER TABLE accounting_posting_exceptions ADD CONSTRAINT fk_ape_property FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(p2, () => r2);

    const p3 = /UPDATE\s+accounting_posting_exceptions\s+e\s+JOIN\s+accounting_subledger_posting_records\s+r\s+ON\s+e\.posting_record_id\s*=\s*r\.id\s+SET\s+e\.property_id\s*=\s*r\.property_id\s+WHERE\s+e\.property_id\s+IS\s+NULL\s+AND\s+r\.property_id\s+IS\s+NOT\s+NULL;/gi;
    const r3 = `UPDATE accounting_posting_exceptions e
SET property_id = r.property_id
FROM accounting_subledger_posting_records r
WHERE e.posting_record_id = r.id
  AND e.property_id IS NULL
  AND r.property_id IS NOT NULL;`;
    out = out.replace(p3, () => r3);
  }

  if (filename.includes('025_front_desk_assignment')) {
    const mysqlFkBlock = /SET\s+@fk_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_res_accepted_fk;/gi;
    const pgFkBlock = `DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT fk_res_assigned_staff FOREIGN KEY (assigned_staff_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT fk_res_accepted_by FOREIGN KEY (accepted_by_user_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(mysqlFkBlock, () => pgFkBlock);
  }

  if (filename.includes('027_booking_proof_verification')) {
    const mysqlFkBlock = /SET\s+@fk_res_declined_named_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_res_room_change_fk;/gi;
    const pgFkBlock = `DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT fk_res_declined_by FOREIGN KEY (declined_by_user_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE reservations ADD CONSTRAINT fk_res_rc_apt FOREIGN KEY (room_change_requested_apartment_id) REFERENCES apartments(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(mysqlFkBlock, () => pgFkBlock);
  }

  if (filename.includes('031_maintenance_evidence')) {
    const mysqlFkBlock = /SET\s+@fk_named_exists[\s\S]*?DEALLOCATE\s+PREPARE\s+stmt_oea_maintenance_fk;/gi;
    const pgFkBlock = `DO $$ BEGIN
  ALTER TABLE operational_evidence_attachments ADD CONSTRAINT fk_oea_maintenance FOREIGN KEY (maintenance_id) REFERENCES maintenance_requests(id) ON DELETE SET NULL;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;`;
    out = out.replace(mysqlFkBlock, () => pgFkBlock);
  }

  // 10. Handle ALTER TABLE ... ADD COLUMN ... with ENUM
  out = out.replace(/ALTER\s+TABLE\s+([a-zA-Z0-9_]+)\s+ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s+ENUM\(([^)]+)\)(\s+NOT\s+NULL)?(\s+DEFAULT\s+'[^']*')?;/gi,
    (match, tbl, col, values, notNull, def) => {
      let res = `ALTER TABLE ${tbl} ADD COLUMN IF NOT EXISTS ${col} VARCHAR(50)${notNull || ''}${def || ''};\n`;
      res += `DO $$ BEGIN\n  ALTER TABLE ${tbl} ADD CONSTRAINT chk_${tbl}_${col} CHECK (${col} IN (${values}));\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;`;
      return res;
    }
  );

  // 11. Handle ALTER TABLE ... MODIFY COLUMN col type -> ALTER TABLE ... ALTER COLUMN col TYPE type
  out = out.replace(/ALTER\s+TABLE\s+([a-zA-Z0-9_]+)\s+MODIFY\s+COLUMN\s+([a-zA-Z0-9_]+)\s+([^;]+);/gi, (match, tbl, col, rest) => {
    const enumMatch = rest.match(/ENUM\(([^)]+)\)/i);
    if (enumMatch) {
      const values = enumMatch[1];
      let defMatch = rest.match(/DEFAULT\s+'([^']+)'/i);
      let defClause = defMatch ? `\nALTER TABLE ${tbl} ALTER COLUMN ${col} SET DEFAULT '${defMatch[1]}';` : '';
      let notNullClause = /NOT\s+NULL/i.test(rest) ? `\nALTER TABLE ${tbl} ALTER COLUMN ${col} SET NOT NULL;` : '';
      return `ALTER TABLE ${tbl} ALTER COLUMN ${col} TYPE VARCHAR(50);${defClause}${notNullClause}
ALTER TABLE ${tbl} DROP CONSTRAINT IF EXISTS chk_${tbl}_${col};
ALTER TABLE ${tbl} DROP CONSTRAINT IF EXISTS ${tbl}_${col}_check;
ALTER TABLE ${tbl} ADD CONSTRAINT chk_${tbl}_${col} CHECK (${col} IN (${values}));`;
    }
    return `ALTER TABLE ${tbl} ALTER COLUMN ${col} TYPE ${rest};`;
  });

  // 12. Convert inline ENUM column definitions to VARCHAR with CHECK constraints in CREATE TABLE
  out = out.replace(/([a-zA-Z0-9_]+)\s+ENUM\(([^)]+)\)(\s+NOT\s+NULL)?(\s+DEFAULT\s+'[^']*')?/gi, (match, col, values, notNull, def) => {
    let res = `${col} VARCHAR(50)${notNull || ''}${def || ''}`;
    res += ` CHECK (${col} IN (${values}))`;
    return res;
  });

  // 13. Extract inline INDEX definitions from CREATE TABLE statements and emit CREATE INDEX
  const createTableRegex = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s*\(([\s\S]*?)\);/gi;
  out = out.replace(createTableRegex, (match, tableName, tableBody) => {
    const lines = tableBody.split('\n');
    const cleanLines = [];
    const indexStatements = [];

    lines.forEach((line) => {
      const idxMatch = line.match(/^\s*INDEX\s+([a-zA-Z0-9_]+)\s*\(([^)]+)\),?\s*$/i);
      const uniqueIdxMatch = line.match(/^\s*UNIQUE\s+INDEX\s+([a-zA-Z0-9_]+)\s*\(([^)]+)\),?\s*$/i);

      if (idxMatch) {
        indexStatements.push(`CREATE INDEX IF NOT EXISTS ${idxMatch[1]} ON ${tableName} (${idxMatch[2]});`);
      } else if (uniqueIdxMatch) {
        indexStatements.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${uniqueIdxMatch[1]} ON ${tableName} (${uniqueIdxMatch[2]});`);
      } else {
        cleanLines.push(line);
      }
    });

    let bodyStr = cleanLines.join('\n');
    bodyStr = bodyStr.replace(/,\s*(\n\s*)$/, '$1');
    bodyStr = bodyStr.replace(/,\s*$/, '');

    let res = `CREATE TABLE IF NOT EXISTS ${tableName} (\n${bodyStr}\n);`;
    if (indexStatements.length > 0) {
      res += '\n\n' + indexStatements.join('\n');
    }
    return res;
  });

  // 14. Convert separate ADD INDEX IF NOT EXISTS (MySQL) -> CREATE INDEX IF NOT EXISTS (PostgreSQL)
  out = out.replace(/ALTER\s+TABLE\s+([a-zA-Z0-9_]+)\s+ADD\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s*\(([^)]+)\);/gi,
    'CREATE INDEX IF NOT EXISTS $2 ON $1 ($3);'
  );
  out = out.replace(/ALTER\s+TABLE\s+([a-zA-Z0-9_]+)\s+ADD\s+UNIQUE\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s*\(([^)]+)\);/gi,
    'CREATE UNIQUE INDEX IF NOT EXISTS $2 ON $1 ($3);'
  );

  // 15. Translate ON DUPLICATE KEY UPDATE to PostgreSQL ON CONFLICT ... DO UPDATE
  if (filename.includes('005_currency_settings')) {
    out = out.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+setting_value\s*=\s*VALUES\(setting_value\)/gi,
      'ON CONFLICT (setting_key) DO UPDATE SET setting_value = EXCLUDED.setting_value'
    );
  }
  if (filename.includes('028_workforce_roster_and_property_media')) {
    out = out.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+name\s*=\s*VALUES\(name\)/gi,
      'ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name'
    );
    out = out.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+description\s*=\s*VALUES\(description\)/gi,
      'ON CONFLICT (name) DO UPDATE SET description = EXCLUDED.description'
    );
  }
  if (filename.includes('031_maintenance_evidence')) {
    out = out.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+description\s*=\s*VALUES\(description\)/gi,
      'ON CONFLICT (setting_key) DO UPDATE SET description = EXCLUDED.description'
    );
  }

  // 16. Convert INSERT IGNORE INTO -> INSERT INTO ... ON CONFLICT DO NOTHING
  out = out.replace(/\bINSERT\s+IGNORE\s+INTO\b/gi, 'INSERT INTO');
  out = out.replace(/\bINSERT\s+IGNORE\b/gi, 'INSERT');

  // Map known tables to their conflict targets
  const conflictTargets = {
    system_settings: '(setting_key)',
    properties: '(id)',
    apartments: '(id)',
    agents: '(id)',
    reservations: '(id)',
    maintenance_requests: '(id)',
    capabilities: '(name)',
    booking_authentications: '(reservation_id)',
    communication_templates: '(name)',
    guests: '(email)',
    expenses: '(id)',
    commissions: '(id)',
    employee_evaluation_criteria: '(code)',
    employees: '(id)',
    employee_profiles: '(employee_id)',
    chat_retention_policies: '(id)',
    accounting_periods: '(period_name)',
    chart_of_accounts: '(id)',
    accounting_account_mappings: '(mapping_key)',
    attendance_policies: '(property_id)'
  };

  Object.entries(conflictTargets).forEach(([tbl, target]) => {
    if (tbl === 'attendance_policies') {
      // Only add to the VALUES statement, not the SELECT NULL statement
      out = out.replace(/(INSERT INTO attendance_policies[\s\S]*?VALUES[\s\S]*?\);)/gi, (m) => {
        if (!m.includes('ON CONFLICT')) {
          return m.replace(/;$/, ` ON CONFLICT ${target} DO NOTHING;`);
        }
        return m;
      });
      return;
    }
    const tblRegex = new RegExp(`(INSERT INTO ${tbl}[\\s\\S]*?\\);)`, 'gi');
    out = out.replace(tblRegex, (m) => {
      if (!m.includes('ON CONFLICT')) {
        return m.replace(/;$/, ` ON CONFLICT ${target} DO NOTHING;`);
      }
      return m;
    });
  });

  // Catch any remaining INSERT INTO public_announcements or other tables without ON CONFLICT
  if (out.includes('INSERT INTO public_announcements')) {
    out = out.replace(/(INSERT INTO public_announcements[\s\S]*?\);)/gi, (m) => {
      if (!m.includes('ON CONFLICT')) {
        return m.replace(/;$/, ' ON CONFLICT DO NOTHING;');
      }
      return m;
    });
  }

  // 17. Clean up any trailing double semicolons or extraneous blank lines
  out = out.replace(/;\s*;/g, ';');

  return out;
}

function processAllMigrations() {
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.sql')).sort();
  console.log(`Translating ${files.length} MySQL migrations to PostgreSQL in ${dstDir}...`);

  files.forEach((file) => {
    const srcPath = path.join(srcDir, file);
    const content = fs.readFileSync(srcPath, 'utf8');
    const translated = translateMySqlToPostgreSql(content, file);
    const dstPath = path.join(dstDir, file);
    fs.writeFileSync(dstPath, translated, 'utf8');
    console.log(`  ✓ Translated ${file}`);
  });

  console.log('All migrations successfully translated to PostgreSQL!');
}

processAllMigrations();
